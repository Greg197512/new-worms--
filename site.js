let currentLang = 'nl';

function pageTitles(lang){
  const t = translations[lang];
  const base = t.brandName;
  const map = {
    'index.html': base + ' — ' + t['hero.tagline'],
    'units.html': base + ' — ' + t['unitspage.title'],
    'gallery.html': base + ' — ' + t['gallerypage.title'],
    'contact.html': base + ' — ' + t['contactpage.title']
  };
  const file = location.pathname.split('/').pop() || 'index.html';
  return map[file] || base;
}

function applyLang(lang){
  currentLang = lang;
  document.documentElement.lang = lang;
  const dict = translations[lang];
  document.querySelectorAll('[data-i18n]').forEach(el=>{
    const key = el.getAttribute('data-i18n');
    if(dict[key] !== undefined){
      el.innerHTML = dict[key];
    }
  });
  document.querySelectorAll('.langswitch button').forEach(b=>{
    b.classList.toggle('active', b.getAttribute('data-lang')===lang);
  });
  document.title = pageTitles(lang);

  // Preserve chosen language across internal navigation via ?lang= param
  document.querySelectorAll('a[data-internal]').forEach(a=>{
    const base = a.getAttribute('data-internal');
    const hash = a.getAttribute('data-hash') || '';
    a.setAttribute('href', lang === 'nl' ? (base + hash) : (base + '?lang=' + lang + hash));
  });
  const url = new URL(window.location);
  if(lang === 'nl'){ url.searchParams.delete('lang'); } else { url.searchParams.set('lang', lang); }
  history.replaceState(null, '', url);
}

function initLangSwitchers(){
  document.querySelectorAll('.langswitch button').forEach(btn=>{
    btn.addEventListener('click', ()=> applyLang(btn.getAttribute('data-lang')));
  });
}

function initNavToggle(){
  const toggle = document.getElementById('navtoggle');
  if(!toggle) return;
  toggle.addEventListener('click', ()=>{
    const links = document.querySelector('.nav-links');
    const isOpen = links.style.display === 'flex';
    links.style.display = isOpen ? 'none' : 'flex';
    links.style.cssText += isOpen ? '' : 'position:absolute;top:68px;left:0;right:0;background:#232529;flex-direction:column;padding:20px 28px;gap:18px;';
  });
}

function initReveal(){
  const io = new IntersectionObserver((entries)=>{
    entries.forEach(e=>{ if(e.isIntersecting){ e.target.classList.add('in'); } });
  },{threshold:0.15});
  document.querySelectorAll('.reveal').forEach(el=>io.observe(el));
}

function initLightbox(){
  const items = document.querySelectorAll('.fg-item, .gitem');
  if(!items.length) return;
  const lb = document.getElementById('lightbox');
  if(!lb) return;
  const lbMedia = lb.querySelector('.lb-media');
  const lbCap = lb.querySelector('.lb-cap');
  let idx = 0;
  const list = Array.from(items);

  function open(i){
    idx = (i + list.length) % list.length;
    const el = list[idx];
    const media = el.querySelector('.gfx-tile') || el.querySelector('img');
    const cap = el.querySelector('.cap');
    lbMedia.innerHTML = '';
    if(media){
      const clone = media.cloneNode(true);
      clone.classList.remove('img-zoom-lock');
      lbMedia.appendChild(clone);
    }
    lbCap.textContent = cap ? cap.textContent : '';
    lb.classList.add('open');
  }
  function close(){ lb.classList.remove('open'); }

  list.forEach((el,i)=> el.addEventListener('click', ()=> open(i)));
  lb.querySelector('.lb-close').addEventListener('click', close);
  lb.querySelector('.lb-prev').addEventListener('click', ()=> open(idx-1));
  lb.querySelector('.lb-next').addEventListener('click', ()=> open(idx+1));
  lb.addEventListener('click', (e)=>{ if(e.target === lb) close(); });
  document.addEventListener('keydown', (e)=>{
    if(!lb.classList.contains('open')) return;
    if(e.key === 'Escape') close();
    if(e.key === 'ArrowRight') open(idx+1);
    if(e.key === 'ArrowLeft') open(idx-1);
  });
}

function initScrollProgress(){
  const bar = document.getElementById('scrollbar');
  if(!bar) return;
  const update = ()=>{
    const h = document.documentElement;
    const scrolled = h.scrollTop;
    const max = h.scrollHeight - h.clientHeight;
    bar.style.width = (max > 0 ? (scrolled / max) * 100 : 0) + '%';
  };
  document.addEventListener('scroll', update, { passive:true });
  window.addEventListener('resize', update);
  update();
}

function initHeroParallax(){
  const bg = document.querySelector('.hero-bg');
  if(!bg || window.matchMedia('(prefers-reduced-motion: reduce)').matches) return;
  const update = ()=>{
    const y = window.scrollY;
    if(y < window.innerHeight * 1.2){
      bg.style.transform = 'translateY(' + (y * 0.18) + 'px)';
    }
  };
  document.addEventListener('scroll', update, { passive:true });
  update();
}

function initBlockReveal(){
  document.querySelectorAll('.block-cover').forEach(cover=>{
    const cols = 10, rows = 6;
    for(let r = 0; r < rows; r++){
      for(let c = 0; c < cols; c++){
        const span = document.createElement('span');
        const delay = (r + c) * 0.035 + Math.random() * 0.05;
        span.style.animationDelay = delay + 's';
        cover.appendChild(span);
      }
    }
  });
}

function initMagneticButtons(){
  document.querySelectorAll('.btn-primary').forEach(btn=>{
    btn.addEventListener('mousemove', (e)=>{
      const r = btn.getBoundingClientRect();
      btn.style.setProperty('--mx', ((e.clientX - r.left) / r.width * 100) + '%');
      btn.style.setProperty('--my', ((e.clientY - r.top) / r.height * 100) + '%');
    });
  });
}

document.addEventListener('DOMContentLoaded', ()=>{
  const params = new URLSearchParams(window.location.search);
  const initial = params.get('lang');
  initLangSwitchers();
  initNavToggle();
  initReveal();
  initLightbox();
  initBlockReveal();
  initScrollProgress();
  initHeroParallax();
  initMagneticButtons();
  applyLang(translations[initial] ? initial : 'nl');
});
